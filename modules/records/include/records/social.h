#pragma once

#include "types.h"

#include <optional>
#include <string>
#include <string_view>

namespace records {

// ── Ключ внешнего объекта (social.md §3) ─────────────────────────────────────
//
// Ролик, пост, страница — то, что живёт вне цепей. Реакции на один ролик
// сходятся, только если каждый вычисляет одинаковый ключ из любой формы ссылки.
// Это вопрос сходимости, а не безопасности: ошибка нормализации разносит
// реакции по двум ключам, но ничего не ломает.

// Форма ключа (records.md §8.11): «пространство:значение» — пространство из
// строчных латинских букв и цифр, до 16 знаков, не схема ссылки (http, https,
// «//» после двоеточия); значение непустое, без пробелов и управляющих знаков.
// Площадку не проверяет — незнакомые пространства законны.
bool is_external_key(std::string_view key) noexcept;

// Ключ из ссылки или готового ключа (social.md §3.1). Ссылка — с http(s):// или
// без схемы; YouTube → yt:ID, Telegram → tg:канал/номер, остальное →
// url:хост/путь?запрос без меток слежки. Ключи yt:, tg:, url: приводятся к
// каноническому виду теми же правилами, незнакомые берутся как есть.
// nullopt — ни ссылка, ни ключ.
std::optional<std::string> external_key(std::string_view link_or_key);

// ── Предмет строкой (social.md §7) ───────────────────────────────────────────

// Ключ — как есть; блок — «ЦЕПЬ/ХЕШ»; цепь — «ЦЕПЬ» (hex строчными).
std::string subject_id(const Subject& s);

// Обратное subject_id: ключ (есть «:»), «ЦЕПЬ/ХЕШ» или «ЦЕПЬ» (64 hex). Ссылок
// не разбирает и ключей не нормализует — это external_key. nullopt — ничто
// из трёх.
std::optional<Subject> parse_subject(std::string_view s);

} // namespace records
