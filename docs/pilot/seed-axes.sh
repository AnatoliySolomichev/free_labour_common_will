#!/usr/bin/env bash
# Служебная цепь осей (ИР-022): словарь труда переезжает из файла агрегатора
# в блоки цепи. Заводит 23 оси из specialty-axes.md §4 — каждую записью AxisDef
# со своим аргументом, потому что ось без аргумента осью не считается.
#
# Это НЕ привилегированный источник. Это одна цепь среди прочих: любой заводит
# свои оси, сила у оси — от употребления, а не от того, кто её записал. Цепь
# существует, чтобы у пилота был с чего начать, и чтобы словарь не жил в коде.
#
#   ./seed-axes.sh [КАТАЛОГ_ДАННЫХ] [--via URL]
set -euo pipefail

BC=${BC:-$(dirname "$0")/../../build/modules/cli/bc}
DATA=${1:-/tmp/bc-axes-chain}
shift || true
VIA=("$@")

"$BC" --data-dir "$DATA" identity create >/dev/null 2>&1 || true

# Печатает «слаг<TAB>цепь/хеш»: ссылка на определение И ЕСТЬ личность оси, и
# именно её подхватывают демо, чтобы расписывать по ней цену.
OUT=${OUT:-}
define() {  # слаг · название · аргумент
  local ref
  ref=$("$BC" --data-dir "$DATA" axis-define --slug "$1" --ru "$2" \
              --description "$3" "${VIA[@]}" | sed -n 's/^axis ref: //p')
  printf '  %-16s %s\n' "$1" "$2" >&2
  if [ -n "$OUT" ]; then printf '%s\t%s\n' "$1" "$ref" >> "$OUT"; fi
}

[ -n "$OUT" ] && : > "$OUT"
echo "── тело ──" >&2
define physical  "Физическая нагрузка" "Мышечное усилие, которого требует час такой работы. Не выносливость (та про длительность) и не темп (тот про скорость): здесь только сила, которую надо приложить."
define endurance "Выносливость"        "Способность держать нагрузку часами без падения качества. Отдельно от физической нагрузки: лёгкая работа может изматывать длительностью, тяжёлая — быть короткой."
define precision "Точность движений"   "Мелкая моторика: цена дрожащей руки. Отдельно от знания — можно понимать, что делать, и не суметь сделать."
define pace      "Темп"                "Скорость, которую работа навязывает исполнителю и которую он не выбирает. Не выносливость: та про то, сколько продержишься, эта про то, с какой частотой."

echo "── предмет труда ──" >&2
define info      "Работа со сведениями" "Предмет труда — символы, тексты, числа, схемы. Не знание: библиотекарь работает со сведениями, не создавая нового."
define people    "Работа с людьми"      "Предмет труда — другой человек, а не вещь. Не эмоциональный труд: хирург работает с человеком, почти не работая с его чувствами."
define nature    "Работа с живым"       "Животные и растения: предмет своеволен, не ждёт и не терпит отсрочки. Отличается от материи именно этим — с доской можно завтра, с телёнком нельзя."
define space     "Работа с пространством" "Предмет — сама среда: земля, помещение, ландшафт. Не «вне помещения» (то про условия), а про то, что изменяют."
define energy    "Работа с энергией"    "Силы природы: ток, тепло, поток, давление. Не опасность: энергией можно управлять безопасно, и она всё равно предмет труда."

echo "── голова ──" >&2
define creativity  "Творчество"        "Насколько работа не повторяет вчерашнюю. Не неопределённость: можно творить в понятных условиях и рутинно действовать в непонятных."
define decision    "Уровень решений"   "От исполнения по инструкции до самостоятельной оценки. Не ответственность: решать и отвечать за последствия — разные вещи, и часто это разные люди."
define uncertainty "Неопределённость"  "Как часто приходится действовать без готового ответа. Не творчество: это про недостаток данных, а не про новизну результата."
define knowledge   "Знание"            "Порог входа: сколько надо выучить, чтобы вообще начать. Не уровень решений: знающий может работать по инструкции."

echo "── риск ──" >&2
define danger         "Опасность"      "Вероятность травмы или гибели САМОГО работника. Не ответственность: та про вред другим. Ось намеренно узкая — «риск вообще» это две оси, склеенные в одну."
define responsibility "Ответственность" "Цена ошибки ДЛЯ ДРУГИХ: от обратимой до непоправимой. Не опасность и не уровень решений."

echo "── среда ──" >&2
define noise     "Шум и вибрация"      "Что среда делает с телом помимо самой работы. Отдельная ось, потому что не зависит от содержания труда."
define confined  "Высота, глубина, теснота" "Работа там, откуда трудно выбраться. Не опасность: в тесноте можно работать безопасно, но она сама по себе тягостна."
define dirt      "Грязь"               "Насколько работа пачкает и чем. Не опасность: грязь бывает безвредной и всё равно неприятной."
define outdoor   "Вне помещения"       "Улица, подземелье, вода — там, где погоду не выключить."
define mobility  "Разъездность"        "От стационарного места до постоянной дороги. Дорога — время жизни, которое работа забирает сверх часов."

echo "── люди вокруг ──" >&2
define teamwork  "Командность"         "От одиночной работы до неразрывной работы в связке, где нельзя остановиться одному."
define emotional "Эмоциональный труд"  "Забота и удержание лица как часть самой работы, а не как черта характера. Не «работа с людьми»: кассир работает с людьми, сиделка — с их состоянием."

echo "── время ──" >&2
define urgency   "Срочность"           "От работы по расписанию до работы по аварии. Забирает не часы, а возможность распоряжаться своими."

{
  echo
  echo "цепь осей: $DATA"
  [ -n "$OUT" ] && echo "ссылки:    $OUT"
  echo "проверить: bc axis-ledger --via URL (столбец described)"
} >&2
