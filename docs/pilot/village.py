#!/usr/bin/env python3
"""
Деревня из восьми человек: каждый час — от сделки до цены оси, по шагам.

Учебный проход по всей цепочке ИР-020 на числах, которые можно пересчитать
на бумаге. Показывает ровно семь шагов:

  1. сделка — люди договорились о цене, больше в системе ничего нет;
  2. корзина — часы и суммы складываются по (специальность × разряд);
  3. нормировка W (economy.md §2б) — средний час сети становится единицей;
  4. профиль — доли объекта труда из каталога, в сумме единица;
  5. подгонка — цены осей вычитываются из ставок, никто их не назначает;
  6. невязка — чего модель не объяснила, и почему это замер, а не доплата;
  7. недостающая ось — как она находится и что значит «ось принята».

Главный урок седьмого шага: по картинке невязок ГЛАЗАМИ ось не видна —
разряд и доли всё перемешивают. Видна она только опытом: добавить столбец и
проверить предсказание на корзине, которой модель не видела.

Восемь корзин на пять осей — почти столько же ручек, сколько фактов; живая
система на таких данных судить отказывается (kMinRowsPerColumn = 10). Пример
существует, чтобы проследить счёт, а не чтобы делать из него выводы.

Запуск:  python3 docs/pilot/village.py
Зависимости: только stdlib (арифметика берётся из axis-prices.py рядом).
"""
import importlib.util
import os
HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("ap", os.path.join(HERE, "axis-prices.py"))
ap = importlib.util.module_from_spec(spec); spec.loader.exec_module(ap)

#  кто     специальность  материя инфо  люди  опасн разряд
PEOPLE = [
    ("Анна",  "программист", 0.0, 1.0, 0.0, 0.00, 4),
    ("Борис", "сварщик",     1.0, 0.0, 0.0, 0.80, 5),
    ("Вера",  "учитель",     0.0, 0.3, 0.7, 0.00, 3),
    ("Глеб",  "повар",       1.0, 0.0, 0.0, 0.10, 2),
    ("Дина",  "врач",        0.0, 0.5, 0.5, 0.20, 6),
    ("Егор",  "грузчик",     1.0, 0.0, 0.0, 0.05, 1),
    ("Жанна", "медсестра",   0.2, 0.3, 0.5, 0.25, 3),
    ("Зоя",   "электрик",    0.9, 0.1, 0.0, 0.40, 4),
]
# сделки месяца: (кто, часов, цена за час — о чём договорились)
DEALS = [("Анна", 40, 1.35), ("Анна", 20, 1.30),
         ("Борис", 50, 1.60), ("Борис", 30, 1.55),
         ("Вера", 60, 1.20), ("Вера", 20, 1.15),
         ("Глеб", 70, 1.00), ("Глеб", 30, 0.95),
         ("Дина", 40, 1.60), ("Дина", 20, 1.55),
         ("Егор", 80, 0.85), ("Егор", 20, 0.90),
         ("Жанна", 50, 1.25), ("Жанна", 30, 1.30),
         ("Зоя", 45, 1.35), ("Зоя", 35, 1.30)]

def line(t): print("\n" + "═" * 76 + f"\n{t}\n" + "═" * 76)

line("ШАГ 1. Сделки. Люди договорились о цене — больше в системе ничего нет.")
print(f"  {'кто':<8}{'часов':>7}{'за час':>9}{'сумма':>10}")
tot = {}
for who, h, r in DEALS:
    a = tot.setdefault(who, [0.0, 0.0]); a[0] += h; a[1] += h * r
    print(f"  {who:<8}{h:>7}{r:>9.2f}{h*r:>10.2f}")

line("ШАГ 2. Корзины: складываем часы и суммы. Корзина = специальность × разряд.")
rows = []
print(f"  {'корзина':<22}{'часов':>7}{'сумма':>10}{'сырая ставка':>15}")
for nm, sp, m, i, p, d, lvl in PEOPLE:
    h, s = tot[nm]
    rows.append(dict(кто=nm, сп=f"{sp} р.{lvl}", m=m, i=i, p=p, d=d,
                     g=(lvl - 1) / 5.0, h=h, s=s, raw=s / h))
    print(f"  {sp + ' р.' + str(lvl):<22}{h:>7.0f}{s:>10.2f}{s/h:>15.4f}")

line("ШАГ 3. Нормировка W: делаем так, чтобы средний час сети равнялся единице.")
H = sum(r["h"] for r in rows); S = sum(r["s"] for r in rows); W = S / H
print(f"  Σчасов = {H:.0f}   Σсумм = {S:.2f}")
print(f"  W = {S:.2f} / {H:.0f} = {W:.6f}   ← столько «сырых» единиц в одном стандартном часе")
print(f"\n  {'корзина':<22}{'сырая':>9}{'÷ W':>10}{'часов':>8}")
for r in rows:
    r["y"] = r["raw"] / W
    print(f"  {r['сп']:<22}{r['raw']:>9.4f}{r['y']:>10.4f}{r['h']:>8.0f}")
print(f"\n  Проверка: Σ(ставка×часы) ÷ Σчасы = "
      f"{sum(r['y']*r['h'] for r in rows)/H:.10f}")

line("ШАГ 4. Профили. Три доли объекта труда дают в сумме единицу.")
print(f"  {'корзина':<22}{'материя':>9}{'инфо':>7}{'люди':>7}{'сумма':>7}{'опасн':>8}{'разряд':>8}{'(р−1)/5':>9}")
for r in rows:
    print(f"  {r['сп']:<22}{r['m']:>9.2f}{r['i']:>7.2f}{r['p']:>7.2f}"
          f"{r['m']+r['i']+r['p']:>7.0f}{r['d']:>8.2f}{r['кто'] and int(r['g']*5+1):>8}{r['g']:>9.2f}")

def fit(cols, title):
    xs = [[r[c] for c in cols] for r in rows]
    ys = [r["y"] for r in rows]; ws = [r["h"] for r in rows]
    b = ap.solve_wls(xs, ys, ws)
    preds = [ap.predict(b, x) for x in xs]
    return b, preds, ap.loo_rmse(xs, ys, ws)

line("ШАГ 5. Подгонка БЕЗ оси опасности — четыре цены на восемь ставок")
cols4 = ["m", "i", "p", "g"]
names4 = ["час работы с материей", "час работы с информацией",
          "час работы с людьми", "прибавка за путь с 1-го разряда до 6-го"]
b4, pred4, loo4 = fit(cols4, "")
for nm, v in zip(names4, b4): print(f"  {nm:<42}{v:>9.4f}")

line("ШАГ 6. Невязки: где модель промахнулась и почему это замер, а не доплата")
print(f"  {'корзина':<22}{'опасн':>7}{'факт':>8}{'модель':>9}{'невязка':>10}{'часов':>7}{'вес×невязка':>13}")
acc = 0.0
for r, pr in zip(rows, pred4):
    r["res4"] = r["y"] - pr; c = r["h"] * r["res4"]; acc += c
    print(f"  {r['сп']:<22}{r['d']:>7.2f}{r['y']:>8.4f}{pr:>9.4f}{r['res4']:>+10.4f}"
          f"{r['h']:>7.0f}{c:>+13.3f}")
print(f"  {'':<46}{'ИТОГО':>19}{acc:>+13.6f}")
print("\n  Невязка есть у всех, и по ней ГЛАЗАМИ ничего не видно:")
for r in sorted(rows, key=lambda r: -r["res4"])[:2]:
    print(f"    {r['сп']:<20} опасность {r['d']:.2f} → невязка {r['res4']:+.4f}")
for r in sorted(rows, key=lambda r: r["res4"])[:2]:
    print(f"    {r['сп']:<20} опасность {r['d']:.2f} → невязка {r['res4']:+.4f}")
print("  У медсестры (опасность 0.25) невязка больше, чем у сварщика (0.80), а у")
print("  врача вовсе минус. Разряд и доли всё перемешали. Поэтому НЕЛЬЗЯ судить")
print("  об оси по картинке невязок — нужен опыт: добавить ось и проверить, стало")
print("  ли предсказание лучше на корзине, которой модель НЕ ВИДЕЛА (шаг 7).")

line("ШАГ 7. Добавляем ось опасности — и невязка схлопывается")
cols5 = ["m", "i", "p", "d", "g"]
b5, pred5, loo5 = fit(cols5, "")
names5 = ["час работы с материей", "час работы с информацией", "час работы с людьми",
          "прибавка за полную опасность", "прибавка за путь с 1-го до 6-го разряда"]
for nm, v in zip(names5, b5): print(f"  {nm:<42}{v:>9.4f}")
print(f"\n  {'корзина':<22}{'невязка без опасности':>24}{'с опасностью':>16}")
for r, pr in zip(rows, pred5):
    print(f"  {r['сп']:<22}{r['res4']:>+24.4f}{r['y']-pr:>+16.4f}")
print(f"\n  Скользящий контроль (ошибка на невиданной корзине, меньше — лучше):")
print(f"    без опасности {loo4:.4f}   с опасностью {loo5:.4f}")
print(f"    планка = {loo4:.4f} × 0.95 = {loo4*0.95:.4f} → "
      f"{'ось ПРИНЯТА' if loo5 < loo4*0.95 else 'ось отклонена'}")
print(f"\n  ВАЖНО: восемь корзин на пять осей — почти столько же ручек, сколько")
print(f"  фактов. Настоящая система на таких данных судить отказывается")
print(f"  (нужно ≥10 наблюдений на столбец). Пример — чтобы проследить счёт.")
